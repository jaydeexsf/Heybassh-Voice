"""Heybassh - Pipecat Voice Agent

This bot uses a cascade pipeline: Speech-to-Text → LLM → Text-to-Speech

Generated by Pipecat CLI

Required AI services:
- Moonshine local (Speech-to-Text)
- Google Gemini (LLM)
- Piper local British voice (Text-to-Speech)

Run the bot using::

    uv run bot.py
"""

